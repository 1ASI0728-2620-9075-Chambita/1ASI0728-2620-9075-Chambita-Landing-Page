export const LANGUAGES = ["en", "es"];

/** English by default (US07); a saved choice or ?lang= wins. */
export function resolveLanguage(queryLanguage, savedLanguage) {
  if (LANGUAGES.includes(queryLanguage)) return queryLanguage;
  if (LANGUAGES.includes(savedLanguage)) return savedLanguage;
  return "en";
}

export function translate(language, key) {
  return messages[language]?.[key] ?? messages.en[key] ?? key;
}

export function htmlLanguage(language) {
  return language === "es" ? "es-419" : "en-US";
}
